#!/usr/bin/env bash

# =============================================================================
# Script:      nano.sh
# Description: Installs nano with syntax highlighting and applies hardened
#              editor settings (backup, locking, secure permissions).
#
# Author:      Bruno Schmid @brulliant
# LinkedIn:    https://www.linkedin.com/in/schmidbruno/
#
# Usage:       ./nano.sh
# =============================================================================

set -euo pipefail

BBlue='\033[1;34m'
BRed='\033[1;31m'
BGreen='\033[1;32m'
NC='\033[0m'

# Must NOT run as root — config goes into user home
if [ "$(id -u)" -eq 0 ]; then
    echo -e "${BRed}Do not run this script as root. Run as your normal user.${NC}" >&2
    exit 1
fi

echo -e "${BBlue}Installing nano and syntax highlighting...${NC}"
sudo pacman -S --needed --noconfirm nano nano-syntax-highlighting

# Create private backup directory
mkdir -p -m 0700 "$HOME/.cache" "$HOME/.cache/nano" "$HOME/.cache/nano/backups"

NANORC="$HOME/.nanorc"

NANORC_NEW="$(mktemp "$HOME/.nanorc.XXXXXX")"

# Write a complete config (idempotent — replaces any previous version)
echo -e "${BBlue}Writing nano configuration...${NC}"
{
    cat << 'EOF'
# Nano configuration — generated by nano.sh

# Backup settings
set backup
set backupdir "~/.cache/nano/backups/"

# Editor behavior
set constantshow
set locking
set nohelp
set nonewlines
set nowrap
set minibar
set zap
set linenumbers
set tabsize 4
set tabstospaces
EOF
    if compgen -G '/usr/share/nano-syntax-highlighting/*.nanorc' >/dev/null; then
        printf '\n# Syntax highlighting (Arch package)\ninclude "/usr/share/nano-syntax-highlighting/*.nanorc"\n'
    fi
} > "$NANORC_NEW"

chmod 600 "$NANORC_NEW"

# A differing ~/.nanorc (hand-written, or a symlink into a dotfiles checkout)
# is kept as a timestamped backup instead of being silently overwritten.
if [[ -e "$NANORC" || -L "$NANORC" ]] && ! cmp -s -- "$NANORC" "$NANORC_NEW"; then
    NANORC_BACKUP="${NANORC}.bak.$(date +%Y%m%d%H%M%S)"
    cp -a -- "$NANORC" "$NANORC_BACKUP"
    echo -e "${BBlue}Existing ${NANORC} saved as ${NANORC_BACKUP}${NC}"
fi
mv -f -- "$NANORC_NEW" "$NANORC"

echo -e "${BGreen}Nano configuration completed successfully.${NC}"
